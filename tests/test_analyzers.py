"""
Unit tests for PacketLens analyzers, run against real synthetic pcap
files (generated by samples/generate_samples.py) — not mocked data.

Run with: python -m pytest tests/ -v
"""

import sys
import os
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent.parent))

import unittest
from core.pcap_parser import parse_pcap, get_capture_summary
from analyzers.port_scan_detector import detect_port_scans
from analyzers.credential_leak_detector import detect_plaintext_credentials
from analyzers.arp_spoof_detector import detect_arp_spoofing
from analyzers.dns_analyzer import analyze_dns_traffic

SAMPLES_DIR = Path(__file__).parent.parent / "samples"


def setUpModule():
    """Ensure sample pcap files exist before running tests."""
    if not (SAMPLES_DIR / "port_scan.pcap").exists():
        sys.path.insert(0, str(SAMPLES_DIR))
        import generate_samples
        generate_samples.generate_port_scan_pcap(str(SAMPLES_DIR / "port_scan.pcap"))
        generate_samples.generate_plaintext_credentials_pcap(str(SAMPLES_DIR / "plaintext_creds.pcap"))
        generate_samples.generate_arp_spoofing_pcap(str(SAMPLES_DIR / "arp_spoofing.pcap"))
        generate_samples.generate_dns_traffic_pcap(str(SAMPLES_DIR / "dns_traffic.pcap"))
        generate_samples.generate_normal_traffic_pcap(str(SAMPLES_DIR / "normal_traffic.pcap"))


class TestPcapParser(unittest.TestCase):
    def test_parses_port_scan_capture(self):
        packets = parse_pcap(str(SAMPLES_DIR / "port_scan.pcap"))
        self.assertEqual(len(packets), 70)
        self.assertEqual(packets[0]["protocol"], "TCP")

    def test_capture_summary_structure(self):
        packets = parse_pcap(str(SAMPLES_DIR / "port_scan.pcap"))
        summary = get_capture_summary(packets)
        self.assertIn("total_packets", summary)
        self.assertIn("protocol_counts", summary)
        self.assertEqual(summary["total_packets"], 70)

    def test_empty_packet_list_summary(self):
        summary = get_capture_summary([])
        self.assertEqual(summary["total_packets"], 0)


class TestPortScanDetector(unittest.TestCase):
    def test_detects_real_port_scan(self):
        packets = parse_pcap(str(SAMPLES_DIR / "port_scan.pcap"))
        findings = detect_port_scans(packets)
        self.assertEqual(len(findings), 1)
        self.assertEqual(findings[0]["source_ip"], "203.0.113.50")
        self.assertEqual(findings[0]["target_ip"], "10.0.0.5")

    def test_no_false_positive_on_normal_traffic(self):
        packets = parse_pcap(str(SAMPLES_DIR / "normal_traffic.pcap"))
        findings = detect_port_scans(packets)
        self.assertEqual(len(findings), 0)

    def test_threshold_respected(self):
        packets = parse_pcap(str(SAMPLES_DIR / "port_scan.pcap"))
        # With a very high threshold, the same traffic should NOT be flagged
        findings = detect_port_scans(packets, port_threshold=1000)
        self.assertEqual(len(findings), 0)


class TestCredentialLeakDetector(unittest.TestCase):
    def test_detects_ftp_credentials(self):
        packets = parse_pcap(str(SAMPLES_DIR / "plaintext_creds.pcap"))
        findings = detect_plaintext_credentials(packets)
        self.assertEqual(len(findings), 2)
        fields = {f["field"] for f in findings}
        self.assertEqual(fields, {"username", "password"})

    def test_captures_actual_credential_value(self):
        packets = parse_pcap(str(SAMPLES_DIR / "plaintext_creds.pcap"))
        findings = detect_plaintext_credentials(packets)
        password_finding = next(f for f in findings if f["field"] == "password")
        self.assertEqual(password_finding["value"], "SuperSecret123")

    def test_no_false_positive_on_encrypted_traffic(self):
        packets = parse_pcap(str(SAMPLES_DIR / "normal_traffic.pcap"))
        findings = detect_plaintext_credentials(packets)
        self.assertEqual(len(findings), 0)


class TestArpSpoofDetector(unittest.TestCase):
    def test_detects_real_arp_spoofing(self):
        packets = parse_pcap(str(SAMPLES_DIR / "arp_spoofing.pcap"))
        findings = detect_arp_spoofing(packets)
        self.assertEqual(len(findings), 1)
        self.assertEqual(findings[0]["claimed_ip"], "10.0.0.1")
        self.assertEqual(len(findings[0]["conflicting_macs"]), 2)

    def test_no_false_positive_on_single_mac_binding(self):
        # normal_traffic.pcap has no ARP packets at all
        packets = parse_pcap(str(SAMPLES_DIR / "normal_traffic.pcap"))
        findings = detect_arp_spoofing(packets)
        self.assertEqual(len(findings), 0)


class TestDnsAnalyzer(unittest.TestCase):
    def test_extracts_queried_domains(self):
        packets = parse_pcap(str(SAMPLES_DIR / "dns_traffic.pcap"))
        result = analyze_dns_traffic(packets)
        self.assertEqual(result["total_queries"], 3)
        self.assertIn("github.com", result["unique_domains"])

    def test_flags_suspicious_keyword_domain(self):
        packets = parse_pcap(str(SAMPLES_DIR / "dns_traffic.pcap"))
        result = analyze_dns_traffic(packets)
        flagged_domains = [f["domain"] for f in result["findings"]]
        self.assertIn("suspicious-c2-domain-xyz123.net", flagged_domains)

    def test_does_not_flag_normal_domains(self):
        packets = parse_pcap(str(SAMPLES_DIR / "dns_traffic.pcap"))
        result = analyze_dns_traffic(packets)
        flagged_domains = [f["domain"] for f in result["findings"]]
        self.assertNotIn("github.com", flagged_domains)
        self.assertNotIn("example.com", flagged_domains)


if __name__ == "__main__":
    unittest.main()
